"use client";

import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";

import { NewDonation } from "@/app/types/donations";

interface AddDonationFormProps {
  onAdd: (donation: NewDonation) => Promise<void> | void;
  onCancel: () => void;
}

function createEmptyDonation(): NewDonation {
  return {
    donor: "",
    amount: 0,
    time: "",
    comment: "",
  };
}

export default function AddDonationForm({ onAdd, onCancel }: AddDonationFormProps) {
  const [newDonation, setNewDonation] = useState<NewDonation>(createEmptyDonation());
  const [saving, setSaving] = useState(false);

  const handleInputChange = (field: keyof NewDonation, value: string | number) => {
    setNewDonation({ ...newDonation, [field]: value });
  };

  const handleSubmit = async () => {
    if (!newDonation.donor.trim() || !newDonation.time || newDonation.amount <= 0) {
      alert("Please enter a donor name, a donation date, and an amount greater than 0.");
      return;
    }

    setSaving(true);
    try {
      await onAdd({ ...newDonation, donor: newDonation.donor.trim() });
      setNewDonation(createEmptyDonation());
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="border rounded-lg p-6 bg-card space-y-6">
      <h2 className="text-lg font-semibold">Add New Donation</h2>

      <div className="grid grid-cols-2 gap-4">
        {/* id is auto-generated by the DB, so no input for it */}

        <div className="space-y-2">
          <Label htmlFor="donor">Donor</Label>
          <Input
            id="donor"
            placeholder="Enter Donor Name"
            value={newDonation.donor}
            onChange={(e) => handleInputChange("donor", e.target.value)}
          />
        </div>

        <div className="space-y-2">
          <Label htmlFor="donation-date">Date Donated</Label>
          <Input
            id="donation-date"
            type="date"
            value={newDonation.time}
            onChange={(e) => handleInputChange("time", e.target.value)}
          />
        </div>

        <div className="space-y-2">
          <Label htmlFor="amount">Amount</Label>
          <Input
            id="amount"
            type="number"
            step="0.01"
            min="0"
            placeholder="0.00"
            value={newDonation.amount || ""}
            onChange={(e) => handleInputChange("amount", parseFloat(e.target.value) || 0)}
          />
        </div>

        <div className="col-span-2 space-y-2">
          <Label htmlFor="comment">Comment</Label>
          <Input
            id="comment"
            placeholder="e.g. EV research, Car Parts (optional)"
            value={newDonation.comment}
            onChange={(e) => handleInputChange("comment", e.target.value)}
          />
        </div>
      </div>

      <div className="flex space-x-4 pt-4">
        <Button onClick={handleSubmit} disabled={saving}>
          {saving ? "Saving..." : "Add Donation"}
        </Button>
        <Button variant="outline" onClick={onCancel} disabled={saving}>
          Cancel
        </Button>
      </div>
    </div>
  );
}
